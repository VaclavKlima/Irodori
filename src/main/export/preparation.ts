import { readFile, mkdir, rm, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import type { FullPreviewResult } from '../preview-types'
import { validateWorkingAsset, workingSourceIdentity, type WorkingAsset } from '../working-assets'
import type { ExportRenderJob } from './types'
import { matchesExportWorkingAsset, validateExportDetailPolicy } from './detail-policy'

interface PreparedSource {
  version: 1
  identity: string
  asset: Omit<WorkingAsset, 'path'>
  backend?: 'cpu' | 'gpu'
  fallback?: string
}

/** Completed source preparation is independent of disposable output and encoder retries. */
export async function prepareExportWorkingSource(
  job: ExportRenderJob,
  signal: AbortSignal,
  decode: (directory: string) => Promise<FullPreviewResult>,
) {
  signal.throwIfAborted()
  validateExportDetailPolicy(job)
  const identity = workingSourceIdentity(job.source.photo.id, job.source.processing)
  if (job.workingAsset && matchesExportWorkingAsset(job.source, job.workingAsset))
    return { ...job.workingAsset, preparation: 'preview-cache' as const }
  const directory = job.preparationDirectory ?? job.directory
  if (job.preparationDirectory) {
    try {
      const entry = JSON.parse(
        await readFile(join(directory, 'source.json'), 'utf8'),
      ) as PreparedSource
      if (entry.version !== 1 || entry.identity !== identity)
        throw new Error('Export preparation identity changed.')
      const asset = { ...entry.asset, path: join(directory, 'linear.f32') }
      if (!asset.hdr) throw new Error('Missing HDR export working descriptor.')
      await validateWorkingAsset(asset, signal)
      return { ...entry, asset, preparation: 'retained' as const }
    } catch {
      signal.throwIfAborted()
      await rm(directory, { recursive: true, force: true })
    }
    await mkdir(directory, { recursive: true })
  }
  let completed = false
  try {
    const frame = await decode(directory)
    if (!frame.linear?.hdr) throw new Error('The RAW decoder returned no HDR master.')
    const descriptor = {
      ...frame.linear,
      width: frame.width,
      height: frame.height,
    }
    const asset: WorkingAsset = {
      ...descriptor,
      path: join(directory, 'linear.f32'),
    }
    // The decoder already checks its generated bytes; retries independently revalidate them.
    const entry: PreparedSource = {
      version: 1,
      identity,
      asset: descriptor,
      backend: frame.diagnostics?.backend,
      fallback: frame.diagnostics?.fallback,
    }
    if (job.preparationDirectory)
      await writeFile(join(directory, 'source.json'), JSON.stringify(entry), { flag: 'wx' })
    completed = true
    return { ...entry, asset, preparation: 'decoded' as const }
  } finally {
    if (!completed && job.preparationDirectory)
      await rm(directory, { recursive: true, force: true })
  }
}
